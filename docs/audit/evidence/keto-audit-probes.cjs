const fs = require('node:fs');
const vm = require('node:vm');
const {createRequire} = require('node:module');
const root = 'C:/Users/HP/Keto-balance';
const req = createRequire(root+'/package.json');
const ts = req('typescript');
const source = fs.readFileSync(root+'/src/App.tsx','utf8');
const extra = '\nglobalThis.audit={RECIPES,genMenu,menuIng,botReply,store,dayISO};';
const compiled = ts.transpileModule(source+extra,{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.React}}).outputText;
const sandbox = {exports:{},require:()=>({}),localStorage:{getItem:()=>null,setItem:()=>{}},console};
vm.runInNewContext(compiled,sandbox);
const {RECIPES,genMenu,menuIng,botReply,store,dayISO}=sandbox.audit;
const out={scope:'Isolated source probes; no network or production data',recipeCount:RECIPES.length};
store.profile.mode='keto'; store.profile.allergies=['Яйца'];
const menu=genMenu('keto',7,3);
const chosen=menu.days.flatMap(d=>Object.values(d.slots)).map(id=>RECIPES.find(r=>r.id===id));
out.eggAllergy={allergies:store.profile.allergies,eggRecipes:chosen.filter(r=>r.ing.some(([n])=>n==='Яйца')).map(r=>r.id)};
store.profile.cookTime=15;
out.timeConstraint={maximum:15,recipesOverLimit:chosen.filter(r=>r.time>15).map(r=>({id:r.id,minutes:r.time}))};
const sample=RECIPES.find(r=>r.id==='k1');
const ingredientMenu={portion:1,days:[{slots:{breakfast:sample.id}}]};
out.portions={recipe:sample.id,recipeServings:sample.serv,requestedServings:1,shoppingEggs:menuIng(ingredientMenu).find(x=>x.name==='Яйца')};
out.negativeCarbDisplays=RECIPES.filter(r=>r.mode==='keto'&&(r.kcal-r.p*4-r.f*9)/4<0).map(r=>({id:r.id,displayed:(r.kcal-r.p*4-r.f*9)/4}));
out.carnivoreMealCount=genMenu('carnivore',7,4).days.map(d=>Object.keys(d.slots).length);
out.chatEmergency={input:'У меня сильная боль в груди и тяжело дышать, что есть на кето?',reply:botReply('У меня сильная боль в груди и тяжело дышать, что есть на кето?')};
out.localDayProbe={date:'2026-10-26T00:30:00+03:00',actual:dayISO(new Date('2026-10-26T00:30:00+03:00'))};
console.log(JSON.stringify(out,null,2));
fs.writeFileSync('C:/Users/HP/AppData/Local/hermes/cache/scratch/keto-audit-probes.json',JSON.stringify(out,null,2));
