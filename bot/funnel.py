from typing import Dict, Any

def calculate_nutrition(weight: float, mode: str = "keto", goal: str = "loss") -> Dict[str, Any]:
    """
    Расчет воды и макронутриентов на основе веса, цели и режима питания.
    """
    # Водный баланс: 30-35 мл на кг веса, минимум 2.0 л для кето/карнивора
    water = max(2.0, round(weight * 0.033, 1))
    
    # Базовый калораж: ~28-30 ккал на кг, минус 15-20% при снижении веса
    base_kcal = weight * 28
    if goal == "loss":
        target_kcal = round(base_kcal * 0.82)
    else:
        target_kcal = round(base_kcal)
        
    if mode == "carnivore":
        # Карнивор: 75% жиры, 25% белки, 0% углеводы
        # 1 г белка = 4 ккал, 1 г жира = 9 ккал
        protein_g = round((target_kcal * 0.28) / 4)
        fat_g = round((target_kcal * 0.72) / 9)
        carbs_g = 0
    else:
        # Кето: 70% жиры, 25% белки, 5% чистые углеводы (до 20-25г)
        protein_g = round((target_kcal * 0.25) / 4)
        fat_g = round((target_kcal * 0.70) / 9)
        carbs_g = min(25, round((target_kcal * 0.05) / 4))
        
    return {
        "weight": weight,
        "mode": mode,
        "water": water,
        "kcal": target_kcal,
        "protein": protein_g,
        "fat": fat_g,
        "carbs": carbs_g,
    }

