export function searchLifehacks(query: string, category = 'Все'): readonly SupplementLifehack[] {
  const q = query.trim().toLocaleLowerCase('ru');
  return SUPPLEMENT_LIFEHACKS.filter(item => (category === 'Все' || item.category === category) &&
    (!q || [item.title, ...(item.aliases || []), item.purpose, item.context, item.caution, item.practical]
      .join(' ').toLocaleLowerCase('ru').includes(q)));
}
